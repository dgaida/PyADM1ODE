# benchmark/eval/make_index.py
"""
Writes ``dataset/index.json`` and refreshes the embedded block in
``viewer/index.html`` with the current datapoints. Run it again after adding or
changing a datapoint:

    python benchmark/eval/make_index.py

Pure stdlib, so it runs anywhere. Lists every *.json under dataset/ that is a
datapoint (has ``reference`` + ``input``), with its path relative to dataset/.
The embedded block in viewer/index.html is replaced between the markers

    // @@BEGIN_EMBEDDED@@
    // @@END_EMBEDDED@@

Everything else in the HTML file stays untouched.
"""

import argparse
import glob
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from validate import report as validate_report  # noqa: E402

DATASET = os.path.abspath(os.path.join(HERE, "..", "dataset"))
VIEWER_HTML = os.path.abspath(os.path.join(HERE, "..", "viewer", "index.html"))

BEGIN_MARKER = "// @@BEGIN_EMBEDDED@@"
END_MARKER = "// @@END_EMBEDDED@@"


def collect_datapoints(dataset: str = DATASET) -> list:
    entries = []
    for path in sorted(glob.glob(os.path.join(dataset, "**", "*.json"), recursive=True)):
        if os.path.basename(path) == "index.json":
            continue
        try:
            with open(path, encoding="utf-8") as fh:
                d = json.load(fh)
        except (json.JSONDecodeError, OSError):
            continue
        if not (isinstance(d, dict) and "reference" in d and "input" in d):
            continue
        entries.append((path, d))
    return entries


def write_index_json(entries: list, dataset: str = DATASET) -> None:
    records = []
    for path, d in entries:
        rel = os.path.relpath(path, dataset).replace(os.sep, "/")
        inp = d.get("input", {})
        records.append(
            {
                "id": d.get("id", rel),
                "path": rel,
                "language": inp.get("language"),
                "modality": inp.get("modality"),
                "regime": d.get("regime"),
            }
        )
    out = os.path.join(dataset, "index.json")
    with open(out, "w", encoding="utf-8") as fh:
        json.dump({"datapoints": records}, fh, ensure_ascii=False, indent=2)
    print(f"{len(records)} Datenpunkte -> {os.path.relpath(out, os.path.join(HERE, '..', '..'))}")


def update_viewer_embedded(entries: list) -> None:
    if not os.path.exists(VIEWER_HTML):
        print(f"Viewer nicht gefunden: {VIEWER_HTML} — uebersprungen")
        return

    with open(VIEWER_HTML, encoding="utf-8") as fh:
        html = fh.read()

    if BEGIN_MARKER not in html or END_MARKER not in html:
        print(f"Marker nicht gefunden in {os.path.basename(VIEWER_HTML)} — embedded-Block nicht aktualisiert")
        return

    datapoints = [d for _, d in entries]
    dp_json = json.dumps(datapoints, ensure_ascii=False, indent=2)

    new_block = (
        f"{BEGIN_MARKER}\n"
        f"// Auto-generated by benchmark/eval/make_index.py — do not edit manually.\n"
        f"const EMBEDDED = {dp_json};\n"
        f"{END_MARKER}"
    )

    pattern = re.compile(
        re.escape(BEGIN_MARKER) + r".*?" + re.escape(END_MARKER),
        re.DOTALL,
    )
    # Use a lambda so re.sub does not process \n in new_block as escape sequences.
    updated, n = pattern.subn(lambda _: new_block, html)
    if n == 0:
        print("Ersetzen fehlgeschlagen — embedded-Block unveraendert")
        return

    with open(VIEWER_HTML, "w", encoding="utf-8") as fh:
        fh.write(updated)
    print(f"viewer/index.html embedded-Block aktualisiert ({len(datapoints)} Datenpunkte)")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.strip().splitlines()[0])
    ap.add_argument(
        "--dataset",
        default=DATASET,
        help="Datensatz-Verzeichnis (Default: benchmark/dataset)",
    )
    ap.add_argument(
        "--no-viewer",
        action="store_true",
        help="viewer/index.html nicht anfassen",
    )
    args = ap.parse_args()
    dataset = os.path.abspath(args.dataset)

    entries = collect_datapoints(dataset)
    write_index_json(entries, dataset)

    # The viewer ships the public dataset inline. Embedding a different
    # dataset would publish it through the viewer, so that only happens for
    # the default directory and never silently.
    if args.no_viewer:
        print("viewer/index.html: uebersprungen (--no-viewer)")
    elif dataset != DATASET:
        print(f"viewer/index.html: uebersprungen ({os.path.basename(dataset)} ist nicht der Standard-Datensatz)")
    else:
        update_viewer_embedded(entries)

    n_bad = validate_report(dataset)
    if n_bad == 0:
        print("Schema-Pruefung: alle Datenpunkte konform")
    return 1 if n_bad else 0


if __name__ == "__main__":
    raise SystemExit(main())
